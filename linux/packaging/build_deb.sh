#!/bin/sh
# Build dist/openrar_<version>_amd64.deb from dist/OpenRAR (run build.sh first, or let it call this).
set -e
cd "$(dirname "$0")/.."
PY=${PY:-.venv/bin/python}
VERSION=$($PY -c "import sys; sys.path.insert(0, '../shared'); import openrar; print(openrar.__version__)")
STAGE=build/deb/openrar_${VERSION}_amd64
rm -rf "$STAGE" && mkdir -p "$STAGE/DEBIAN" "$STAGE/opt" "$STAGE/usr/bin"
cp -a dist/OpenRAR "$STAGE/opt/openrar"
ln -s /opt/openrar/openrar "$STAGE/usr/bin/openrar"
ln -s /opt/openrar/orar "$STAGE/usr/bin/orar"
# applications menu, icons, MIME type, Dolphin and Nemo menus: generated by the same code as per-user setup
PYTHONPATH=.:../shared $PY - "$STAGE/usr/share" <<'PYEOF'
import sys
from openrar.integration import DEFAULT_ASSOCIATIONS
from openrar_linux import desktop
cfg = {"cascaded": True, "add": True, "add_quick": True, "extract": True, "extract_here": True,
       "extract_to": True, "test": True, "associate": DEFAULT_ASSOCIATIONS}
desktop.refresh = lambda data: None
desktop.install(cfg, ["/usr/bin/openrar"], "../shared/openrar/resources/icon.png", data=sys.argv[1], per_user=False)
PYEOF
mkdir -p "$STAGE/usr/share/doc/openrar"
cp ../LICENSE "$STAGE/usr/share/doc/openrar/copyright"
SIZE=$(du -sk "$STAGE" | cut -f1)
cat > "$STAGE/DEBIAN/control" <<CTRL
Package: openrar
Version: $VERSION
Section: utils
Priority: optional
Architecture: amd64
Maintainer: Vinoth Kannah MP <1297213+chaoszero6@users.noreply.github.com>
Installed-Size: $SIZE
Depends: libc6 (>= 2.31), libstdc++6, libgl1, libegl1, libfontconfig1, libdbus-1-3, libglib2.0-0 | libglib2.0-0t64, libx11-6, libx11-xcb1, libxkbcommon0, libxkbcommon-x11-0, libxcb1, libxcb-cursor0, libxcb-icccm4, libxcb-image0, libxcb-keysyms1, libxcb-randr0, libxcb-render0, libxcb-render-util0, libxcb-shape0, libxcb-shm0, libxcb-sync1, libxcb-util1, libxcb-xfixes0, libxcb-xkb1
Recommends: 7zip | p7zip-full, unrar | unrar-free, zenity
Homepage: https://github.com/chaoszero6/openrar
Description: Archive manager for ZIP, 7Z, RAR, TAR and more
 OpenRAR creates ZIP, 7Z and TAR archives (with AES-256 encryption, split volumes,
 recovery records and self-extracting archives) and opens and extracts RAR, ISO,
 CAB and other formats. Includes the orar command-line tool and file-manager
 menus for Dolphin, Nemo and GNOME Files.
CTRL
cat > "$STAGE/DEBIAN/postinst" <<'POST'
#!/bin/sh
set -e
command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database -q /usr/share/applications || true
command -v update-mime-database >/dev/null 2>&1 && update-mime-database /usr/share/mime || true
command -v gtk-update-icon-cache >/dev/null 2>&1 && gtk-update-icon-cache -q -t /usr/share/icons/hicolor || true
exit 0
POST
cp "$STAGE/DEBIAN/postinst" "$STAGE/DEBIAN/postrm"
chmod 755 "$STAGE/DEBIAN/postinst" "$STAGE/DEBIAN/postrm"
find "$STAGE" -type d -exec chmod 755 {} +
fakeroot dpkg-deb --build -Zxz "$STAGE" "dist/openrar_${VERSION}_amd64.deb" >/dev/null
echo "dist/openrar_${VERSION}_amd64.deb"
